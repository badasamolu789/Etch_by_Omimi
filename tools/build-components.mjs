import { readFileSync, writeFileSync } from 'node:fs';
const paths = {
    headerHTML: 'component/header.html', footerHTML: 'component/footer.html',
    sidebarHTML: 'user/component/sidebar.html', topbarHTML: 'user/component/topbar.html',
    getAdminSidebarHTML: 'admin/component/sidebar.html', getAdminTopbarHTML: 'admin/component/topbar.html',
};
const components = Object.fromEntries(Object.entries(paths).map(([key, path]) => [key, readFileSync(new URL('../' + path, import.meta.url), 'utf8').trimEnd()]));
const content = '// Generated by node tools/build-components.mjs. Edit component HTML sources.\nwindow.EtchComponents = ' + JSON.stringify(components, null, 2) + ';\n';
const output = new URL('../script/components.js', import.meta.url);
if (process.argv.includes('--check')) {
    if (readFileSync(output, 'utf8') !== content) throw new Error('Components are stale. Run node tools/build-components.mjs');
} else writeFileSync(output, content);
